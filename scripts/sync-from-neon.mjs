/**
 * Read-only sync: shared Neon → mobile fallback catalog.
 * Never runs DDL / migrations (safe for web).
 *
 * Usage: npm run db:sync
 */
import fs from 'fs';
import path from 'path';
import { config } from 'dotenv';
import { neon } from '@neondatabase/serverless';

config({ path: '.env' });

const url = process.env.DATABASE_URL?.trim();
if (!url) {
  console.error('DATABASE_URL missing');
  process.exit(1);
}

const sql = neon(url);
const orgIdEnv = process.env.PLATFORM_ORG_ID?.trim();

const org =
  orgIdEnv
    ? (
        await sql`select id, name, slug from organization where id = ${orgIdEnv} limit 1`
      )[0]
    : (
        await sql`select id, name, slug from organization where name = 'NULLXES' limit 1`
      )[0];

if (!org) {
  console.error('NULLXES org not found — abort (no writes)');
  process.exit(1);
}

const rows = await sql`
  select
    e.id,
    e.name,
    e.role,
    e.status::text as status,
    e.organization_id,
    a.config as avatar_config,
    s.provider_id as session_provider_id,
    s.config as session_config
  from digital_employee e
  left join employee_provider_config a
    on a.employee_id = e.id and a.provider_type = 'avatar'
  left join employee_provider_config s
    on s.employee_id = e.id and s.provider_type = 'session'
  where e.organization_id = ${org.id}
  order by e.name
`;

function initials(name) {
  const parts = name
    .replace(/NULLXES/gi, '')
    .trim()
    .split(/\s+/)
    .filter(Boolean);
  if (!parts.length) return 'NX';
  if (parts.length === 1) return parts[0].slice(0, 2).toUpperCase();
  return `${parts[0][0] ?? ''}${parts[1][0] ?? ''}`.toUpperCase();
}

function resolveVoiceMode(sessionProviderId, sessionConfig) {
  const voiceId = sessionConfig?.voiceId;
  const studioVoiceId = sessionConfig?.studioVoiceId;
  const provider = sessionConfig?.voiceProvider || sessionProviderId;
  if (provider === 'elevenlabs' && voiceId && studioVoiceId) return 'elevenlabs';
  return 'anam';
}

const present = new Set(
  Object.keys(process.env).filter(
    (k) => /^ANAM_API_KEY(_\d+)?$/.test(k) && process.env[k]?.trim(),
  ),
);

const employees = rows.map((r) => {
  const avatar = r.avatar_config ?? {};
  const session = r.session_config ?? {};
  const meta = avatar.providerMetadata ?? {};
  const slot = typeof meta.anamApiKeySlot === 'string' ? meta.anamApiKeySlot : null;
  const ready = Boolean(
    avatar.provisioningStatus === 'ready' &&
      avatar.avatarId &&
      avatar.personaId &&
      slot &&
      present.has(slot),
  );

  return {
    id: r.id,
    name: r.name,
    role: r.role,
    status: r.status,
    initials: initials(r.name),
    avatarId: avatar.avatarId ?? null,
    personaId: avatar.personaId ?? null,
    anamSlot: slot,
    previewUrl: avatar.previewUrl ?? null,
    anamReady: ready,
    organizationId: r.organization_id,
    voiceMode: resolveVoiceMode(r.session_provider_id, session),
    voiceId: session.voiceId ?? null,
    studioVoiceId: session.studioVoiceId ?? null,
  };
});

const kaira = employees.find((e) => e.name === 'Kaira NULLXES');
const defaultId = kaira?.id ?? employees.find((e) => e.anamReady)?.id ?? employees[0]?.id;

const snapshot = {
  syncedAt: new Date().toISOString(),
  org,
  envSlotsPresent: [...present].sort(),
  defaultEmployeeId: defaultId,
  employees,
};

const dataDir = path.join('src', 'features', 'workforce', 'data');
fs.mkdirSync(dataDir, { recursive: true });
fs.writeFileSync(path.join(dataDir, '_neon-snapshot.json'), JSON.stringify(snapshot, null, 2) + '\n');

function lit(value) {
  return JSON.stringify(value);
}

const employeeBlocks = employees
  .map((e) => {
    return `  {
    id: ${lit(e.id)},
    name: ${lit(e.name)},
    role: ${lit(e.role)},
    status: ${lit(e.status)},
    initials: ${lit(e.initials)},
    avatarId: ${lit(e.avatarId)},
    personaId: ${lit(e.personaId)},
    anamSlot: ${lit(e.anamSlot)},
    previewUrl: ${lit(e.previewUrl)},
    anamReady: ${e.anamReady},
    organizationId: NULLXES_ORG_ID,
    voiceMode: ${lit(e.voiceMode)},
    voiceId: ${lit(e.voiceId)},
    studioVoiceId: ${lit(e.studioVoiceId)},
  }`;
  })
  .join(',\n');

const ts = `/**
 * Offline / bootstrap fallback for NULLXES org employees.
 * Regenerated by \`npm run db:sync\` from shared Neon (read-only — never mutates web DB).
 * Synced: ${snapshot.syncedAt}
 */

import type { DigitalEmployee } from '@/features/workforce/types';

export type { AnamSlot, DigitalEmployee, EmployeeStatus } from '@/features/workforce/types';

/** NULLXES org on shared Neon. */
export const NULLXES_ORG_ID = ${lit(org.id)};

/** Default Talk/Live employee. */
export const DEFAULT_EMPLOYEE_ID = ${lit(defaultId)};

/**
 * Snapshot from Neon org NULLXES.
 * anamReady = provisioning ready AND slot key present in local server env.
 * voiceMode=elevenlabs → EL PCM into Anam mouth (not EL Conversational Agents).
 */
export const FALLBACK_EMPLOYEES: DigitalEmployee[] = [
${employeeBlocks},
];

/** @deprecated use FALLBACK_EMPLOYEES */
export const DIGITAL_EMPLOYEES = FALLBACK_EMPLOYEES;

export const WORKFORCE_STATS = {
  active: FALLBACK_EMPLOYEES.filter((e) => e.status === 'active').length,
  live: 0,
  sessions: 0,
} as const;

export function getFallbackEmployee(id: string) {
  return FALLBACK_EMPLOYEES.find((employee) => employee.id === id) ?? null;
}

export function getReadyFallbackEmployee(id: string) {
  const employee = getFallbackEmployee(id);
  return employee?.anamReady ? employee : null;
}

export function getEmployee(id: string) {
  return getFallbackEmployee(id);
}

export function getReadyEmployee(id: string) {
  return getReadyFallbackEmployee(id);
}
`;

fs.writeFileSync(path.join(dataDir, 'employees.ts'), ts);

console.log('host', new URL(url).host);
console.log('org', org.name, org.id);
console.log('employees', employees.length);
for (const e of employees) {
  console.log(
    `  ${e.anamReady ? 'OK' : '--'} ${e.name} | ${e.anamSlot ?? 'no-slot'} | ${e.voiceMode}`,
  );
}
console.log('wrote src/features/workforce/data/employees.ts');
console.log('wrote src/features/workforce/data/_neon-snapshot.json');
console.log('DDL: none (web schema untouched)');
